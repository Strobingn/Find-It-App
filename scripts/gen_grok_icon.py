def vd(els,mono=False):
    out=['<?xml version="1.0" encoding="utf-8"?>','<!-- Find It Grok launcher: topo-contour magnifier. Generated by scripts (see commit). -->',
         '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for p,f,s,w,a in els:
        attrs=[f'android:pathData="{p}"']
        if f: attrs.append(f'android:fillColor="{"#FFFFFFFF" if mono else f}"')
        if s: attrs+= [f'android:strokeColor="{"#FFFFFFFF" if mono else s}"',f'android:strokeWidth="{w}"','android:strokeLineCap="round"','android:strokeLineJoin="round"']
        if a<1: attrs.append(f'android:strokeAlpha="{a}"')
        out.append('    <path '+' '.join(attrs)+' />')
    out.append('</vector>');return '\n'.join(out)+'\n'
def svg(els,size,clip_circle=False):
    b=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="9 9 90 90">']
    if clip_circle: b.append('<clipPath id="c"><circle cx="54" cy="54" r="45"/></clipPath><g clip-path="url(#c)">')
    for p,f,s,w,a in els:
        b.append(f'<path d="{p}" fill="{f or "none"}" stroke="{s or "none"}" stroke-width="{w}" stroke-opacity="{a}" stroke-linecap="round" stroke-linejoin="round"/>')
    if clip_circle: b.append('</g>')
    b.append('</svg>');return ''.join(b)
