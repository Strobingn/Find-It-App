def loop(cx,cy,r,wob,ph,n=48):
    pts=[]
    for i in range(n):
        t=2*math.pi*i/n
        rr=r*(1+wob*math.sin(3*t+ph)+wob*0.5*math.cos(2*t-ph))
        pts.append((cx+rr*math.cos(t),cy+rr*math.sin(t)*0.9))
    return 'M'+' L'.join(f'{x:.2f},{y:.2f}' for x,y in pts)+' Z'
